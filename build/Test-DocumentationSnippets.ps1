[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string] $RepositoryPath
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repository = (Resolve-Path -LiteralPath $RepositoryPath).Path
$samplesPath = Join-Path $repository 'tests/Reservoir.Docs.Samples'
$ignoredPathPattern = '[\\/](?:\.git|artifacts|bin|node_modules|obj)[\\/]'
$markdownFiles = @(
    Get-ChildItem -LiteralPath $repository -Filter '*.md' -File -Recurse |
        Where-Object { $_.FullName -notmatch $ignoredPathPattern }
)
$sampleFiles = @(Get-ChildItem -LiteralPath $samplesPath -Filter '*.cs')

function ConvertTo-NormalizedSnippet {
    param([string[]] $Lines)

    return (($Lines | ForEach-Object { $_.Trim() }) -join "`n").Trim()
}

$compiledSamples = ($sampleFiles | ForEach-Object {
    ConvertTo-NormalizedSnippet -Lines @(Get-Content -LiteralPath $_.FullName)
}) -join "`n<sample-file-boundary>`n"
$failures = [System.Collections.Generic.List[string]]::new()
$snippetCount = 0

foreach ($markdownFile in $markdownFiles) {
    $lines = @(Get-Content -LiteralPath $markdownFile.FullName)
    $snippetStart = 0
    $snippetLines = [System.Collections.Generic.List[string]]::new()

    for ($index = 0; $index -lt $lines.Count; $index++) {
        $line = $lines[$index]

        if ($snippetStart -eq 0) {
            if ($line -match '^```csharp(?:\s.*)?$') {
                $snippetStart = $index + 1
                $snippetLines.Clear()
            }

            continue
        }

        if ($line -ne '```') {
            $snippetLines.Add($line)
            continue
        }

        $snippetCount++
        $snippet = ConvertTo-NormalizedSnippet -Lines $snippetLines
        if ([string]::IsNullOrWhiteSpace($snippet)) {
            $failures.Add("$($markdownFile.FullName):$snippetStart contains an empty C# snippet.")
        }
        elseif (-not $compiledSamples.Contains($snippet, [StringComparison]::Ordinal)) {
            $failures.Add("$($markdownFile.FullName):$snippetStart is not present in compiled documentation samples.")
        }

        $snippetStart = 0
    }

    if ($snippetStart -ne 0) {
        $failures.Add("$($markdownFile.FullName):$snippetStart has no closing fence.")
    }
}

foreach ($sampleFile in $sampleFiles) {
    $content = Get-Content -LiteralPath $sampleFile.FullName -Raw
    if ($content -match '(?m)^\s*#(?:if|elif|else|endif)\b') {
        $failures.Add("$($sampleFile.FullName) uses conditional compilation.")
    }

    if ($content -match '/\*|\*/') {
        $failures.Add("$($sampleFile.FullName) uses a block comment that could hide a snippet.")
    }
}

$validationFiles = @(
    Get-ChildItem -LiteralPath $repository -File -Recurse |
        Where-Object {
            $_.FullName -notmatch $ignoredPathPattern -and
            ($_.Extension -in @('.cs', '.csproj', '.props', '.targets', '.ruleset', '.yml', '.yaml') -or
             $_.Name -in @('.editorconfig', '.globalconfig'))
        }
)

foreach ($validationFile in $validationFiles) {
    $content = Get-Content -LiteralPath $validationFile.FullName -Raw

    if ($validationFile.Extension -eq '.cs') {
        if ($content -match '(?m)^\s*#pragma\s+warning\s+disable\b') {
            $failures.Add("$($validationFile.FullName) disables compiler warnings.")
        }

        if ($content -match '\[(?:[\w.]+\.)?(?:Unconditional)?SuppressMessage') {
            $failures.Add("$($validationFile.FullName) uses a suppression attribute.")
        }

        if ($content -match '(?m)^\s*//\s*<auto-generated\s*/?>') {
            $failures.Add("$($validationFile.FullName) masks analyzer coverage as generated code.")
        }

        if ($content -match '\[(?:[\w.]+\.)?(?:ExcludeFromCodeCoverage|DebuggerNonUserCode)') {
            $failures.Add("$($validationFile.FullName) masks test or debugger coverage.")
        }

        if ($content -match '(?i)\bSkip\s*=') {
            $failures.Add("$($validationFile.FullName) skips a test.")
        }
    }

    if ($validationFile.Extension -in @('.csproj', '.props', '.targets')) {
        foreach ($propertyName in @('NoWarn', 'WarningsNotAsErrors', 'MSBuildWarningsAsMessages')) {
            $matches = [regex]::Matches(
                $content,
                "<$propertyName\b[^>]*>(?<value>.*?)</$propertyName>",
                [Text.RegularExpressions.RegexOptions]::Singleline)

            foreach ($match in $matches) {
                if (-not [string]::IsNullOrWhiteSpace($match.Groups['value'].Value)) {
                    $failures.Add("$($validationFile.FullName) sets non-empty $propertyName.")
                }
            }
        }

        if ($content -match '<(?:TreatWarningsAsErrors|EnableNETAnalyzers|RunAnalyzersDuringBuild|ILLinkTreatWarningsAsErrors|IlcTreatWarningsAsErrors)>\s*false\s*</' -or
            $content -match '<(?:SuppressTrimAnalysisWarnings|SuppressAotAnalysisWarnings|TrimmerSingleWarn)>\s*true\s*</') {
            $failures.Add("$($validationFile.FullName) disables warning or analyzer failures.")
        }
    }

    if ($validationFile.Name -in @('.editorconfig', '.globalconfig') -and
        $content -match '(?im)^\s*dotnet_diagnostic\..*\.severity\s*=\s*(?:none|silent)\s*$') {
        $failures.Add("$($validationFile.FullName) disables or silences an analyzer diagnostic.")
    }

    if ($validationFile.Extension -in @('.yml', '.yaml') -and
        $content -match '(?im)continue-on-error\s*:\s*true|--skip-duplicate|SilentlyContinue|IgnoreExitCode') {
        $failures.Add("$($validationFile.FullName) masks a CI command failure.")
    }
}

if ($failures.Count -gt 0) {
    throw "Documentation snippet validation failed:`n$($failures -join "`n")"
}

Write-Host "Validated $snippetCount compiled C# documentation snippets without masking."
